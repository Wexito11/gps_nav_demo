#!/usr/bin/env python3
"""Generate config/nav2_params.yaml from the stock Nav2 Jazzy params + our overrides.

Why a generator: the stock file stays the single source of truth for everything we don't
touch, and every deviation from it is listed explicitly below (easy to review).
"""
import sys
from pathlib import Path

import yaml

SRC = Path(sys.argv[1] if len(sys.argv) > 1 else
           '/opt/ros/jazzy/share/nav2_bringup/params/nav2_params.yaml')
DST = Path(__file__).resolve().parent.parent / 'config' / 'nav2_params.yaml'

ROBOT_RADIUS = 0.30          # rover is 0.42 x 0.38 m


class NoAliasDumper(yaml.SafeDumper):
    """ROS 2 (rcl) YAML parser does not support anchors/aliases (&id001 / *id001)."""

    def ignore_aliases(self, data):
        return True


p = yaml.safe_load(SRC.read_text())

# 1) Our Gazebo bridge expects geometry_msgs/TwistStamped on /cmd_vel
for node in p.values():
    if isinstance(node, dict) and 'ros__parameters' in node:
        node['ros__parameters']['enable_stamped_cmd_vel'] = True


# 2) Obstacle sources: 2D lidar + depth camera point cloud, fused in a 3D voxel layer.
#    3D matters: the lidar ray at 0.20 m passes OVER the 8 cm curb and, in a 2D layer,
#    would clear what the camera marked. In voxels it only clears its own height.
def scan_src(max_range):
    return {'topic': '/scan', 'data_type': 'LaserScan', 'marking': True, 'clearing': True,
            'min_obstacle_height': 0.0, 'max_obstacle_height': 0.8,
            'obstacle_min_range': 0.0, 'obstacle_max_range': max_range,
            'raytrace_min_range': 0.0, 'raytrace_max_range': max_range + 1.0}


def depth_src():
    return {'topic': '/camera/points', 'data_type': 'PointCloud2', 'marking': True,
            'clearing': True,
            'min_obstacle_height': 0.04,   # drop the ground, keep the 8 cm curb
            'max_obstacle_height': 0.8,
            'obstacle_min_range': 0.0, 'obstacle_max_range': 3.0,
            'raytrace_min_range': 0.0, 'raytrace_max_range': 4.0}


def voxel_layer(scan_range):
    return {'plugin': 'nav2_costmap_2d::VoxelLayer', 'enabled': True,
            'publish_voxel_map': False, 'origin_z': 0.0,
            'z_resolution': 0.05, 'z_voxels': 16, 'max_obstacle_height': 0.8,
            'mark_threshold': 0, 'observation_sources': 'scan depth',
            'scan': scan_src(scan_range), 'depth': depth_src()}


INFLATION = {'plugin': 'nav2_costmap_2d::InflationLayer',
             'inflation_radius': 0.6, 'cost_scaling_factor': 4.0}

# 3) Local costmap (odom frame)
lc = p['local_costmap']['local_costmap']['ros__parameters']
lc.pop('static_layer', None)
lc.update({'width': 4, 'height': 4, 'resolution': 0.05, 'robot_radius': ROBOT_RADIUS,
           'plugins': ['voxel_layer', 'inflation_layer'],
           'voxel_layer': voxel_layer(3.0), 'inflation_layer': dict(INFLATION)})

# 4) Global costmap (map frame) WITHOUT a prior map: rolling window built online from sensors.
#    30 x 30 m must contain every pair of consecutive waypoints.
gc = p['global_costmap']['global_costmap']['ros__parameters']
for k in ('static_layer', 'obstacle_layer'):
    gc.pop(k, None)
gc.update({'rolling_window': True, 'width': 30, 'height': 30, 'resolution': 0.1,
           'track_unknown_space': False, 'robot_radius': ROBOT_RADIUS,
           'update_frequency': 2.0, 'publish_frequency': 1.0,
           'plugins': ['voxel_layer', 'inflation_layer'],
           'voxel_layer': voxel_layer(8.0), 'inflation_layer': dict(INFLATION)})

# 5) Planner: A* on the rolling costmap
p['planner_server']['ros__parameters']['GridBased'].update(
    {'use_astar': True, 'allow_unknown': True, 'tolerance': 0.5})

# 6) MPPI controller: lighter for a laptop CPU, no trajectory markers
fp = p['controller_server']['ros__parameters']['FollowPath']
fp.update({'batch_size': 1000, 'visualize': False, 'vx_max': 0.5})

DST.write_text('# GENERATED by tools/make_nav2_params.py from the stock Nav2 Jazzy params.\n'
               '# Edit the generator, not this file.\n'
               + yaml.dump(p, Dumper=NoAliasDumper, sort_keys=False, default_flow_style=False))
print(f'written {DST}')
